package com.openbravo.pos.data;

import com.openbravo.basic.BasicException;
import com.openbravo.data.loader.Session;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.ValueSource;
import static org.junit.jupiter.api.Assertions.*;

class OrdersMigrationCompatibilityTest {
    private static final String LEGACY_CHECKSUM = "9:e9b9b069ca8f50a61072fc15f2b6b39d";
    @TempDir Path directory;

    @ParameterizedTest
    @ValueSource(strings = {"hsqldb", "sqlite"})
    void upgradesKnownLegacySchemaWithoutLosingOrdersOrReusingIds(String engine) throws Exception {
        Class.forName(engine.equals("sqlite") ? "org.sqlite.JDBC" : "org.hsqldb.jdbc.JDBCDriver");
        String url = engine.equals("sqlite") ? "jdbc:sqlite:" + directory.resolve("store.db")
                : "jdbc:hsqldb:file:" + directory.resolve("store");
        Session session = new Session(url, engine.equals("hsqldb") ? "SA" : null, "");
        try {
            DBMigrator.execDBMigration(session); // Fresh installations must also migrate successfully.
            try (var sql = session.getConnection().createStatement()) {
                sql.execute("DROP TABLE orders");
                String identity = engine.equals("sqlite")
                        ? "INTEGER PRIMARY KEY AUTOINCREMENT NOT NULL"
                        : "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY";
                sql.execute("CREATE TABLE orders (id " + identity
                        + ", orderid VARCHAR(50), qty INT DEFAULT 1, details VARCHAR(255),"
                        + " attributes VARCHAR(255), notes VARCHAR(255), ticketid VARCHAR(50),"
                        + " ordertime DATETIME NOT NULL, displayid INT DEFAULT 1, auxiliary INT, completetime DATETIME)");
                sql.executeUpdate("INSERT INTO orders (id, orderid, qty, details, attributes, notes, ticketid, ordertime, displayid, auxiliary)"
                        + " VALUES (10, 'old-order', 2, 'Coffee', 'Large', 'No sugar', 'ticket-1', '2026-10-24 10:30:00', 3, 1)");
                sql.executeUpdate("INSERT INTO orders (id, orderid, ordertime) VALUES (99, 'deleted-order', '2026-10-24 10:30:00')");
                sql.executeUpdate("DELETE FROM orders WHERE id = 99");
                if (engine.equals("hsqldb")) sql.execute("ALTER TABLE orders ALTER COLUMN id RESTART WITH 100");
                sql.executeUpdate("UPDATE DATABASECHANGELOG SET MD5SUM = '" + LEGACY_CHECKSUM
                        + "' WHERE ID = '1603928315936-19'");
                sql.executeUpdate("DELETE FROM DATABASECHANGELOG WHERE ID LIKE '20261101-orders-column-types%'");
            }
            DBMigrator.execDBMigration(session);
            try (var sql = session.getConnection().createStatement();
                 var row = sql.executeQuery("SELECT * FROM orders WHERE id = 10")) {
                assertTrue(row.next());
                assertEquals(2.0, row.getDouble("qty"));
                assertEquals("3", row.getString("displayid"));
                assertEquals("Coffee", row.getString("details"));
                assertEquals("Large", row.getString("attributes"));
                assertEquals("No sugar", row.getString("notes"));
                assertEquals("ticket-1", row.getString("ticketid"));
                assertEquals(1, row.getInt("auxiliary"));
                assertNull(row.getString("completetime"));
                assertTrue(row.getString("ordertime").startsWith("2026-10-24 10:30:00"));
            }
            try (var sql = session.getConnection().createStatement()) {
                sql.executeUpdate("INSERT INTO orders (orderid, qty, displayid, ordertime)"
                        + " VALUES ('fractional', 1.25, 'screen-A', '2026-11-01 10:30:00')");
                sql.executeUpdate("INSERT INTO orders (orderid, displayid, ordertime)"
                        + " VALUES ('leading-zero', '001', '2026-11-01 10:30:00')");
                sql.executeUpdate("INSERT INTO orders (orderid, ordertime) VALUES ('defaults', '2026-11-01 10:30:00')");
            }
            assertUpgradedOrders(session);
        } finally { shutdown(session, engine); }
        Session reopened = new Session(url, engine.equals("hsqldb") ? "SA" : null, "");
        try {
            DBMigrator.execDBMigration(reopened);
            assertUpgradedOrders(reopened);
        } finally { shutdown(reopened, engine); }
    }

    @Test
    void unrelatedChecksumsStillFailValidation() throws Exception {
        Class.forName("org.hsqldb.jdbc.JDBCDriver");
        Session session = new Session("jdbc:hsqldb:mem:orders-checksum-guard", "SA", "");
        try {
            DBMigrator.execDBMigration(session);
            try (var sql = session.getConnection().createStatement()) {
                sql.executeUpdate("UPDATE DATABASECHANGELOG SET MD5SUM = '9:00000000000000000000000000000000'"
                        + " WHERE ID = '1603928315936-19'");
            }
            assertThrows(BasicException.class, () -> DBMigrator.execDBMigration(session));
        } finally { shutdown(session, "hsqldb"); }
    }

    private static void assertUpgradedOrders(Session session) throws Exception {
        try (var sql = session.getConnection().createStatement();
             var row = sql.executeQuery("SELECT id, qty, displayid FROM orders WHERE orderid = 'fractional'")) {
            assertTrue(row.next());
            assertTrue(row.getInt("id") >= 100, "deleted order IDs must not be reused");
            assertEquals(1.25, row.getDouble("qty"));
            assertEquals("screen-A", row.getString("displayid"));
        }
        try (var sql = session.getConnection().createStatement();
             var row = sql.executeQuery("SELECT qty, displayid FROM orders WHERE orderid = 'leading-zero'")) {
            assertTrue(row.next());
            assertEquals(1.0, row.getDouble("qty"));
            assertEquals("001", row.getString("displayid"));
        }
        try (var sql = session.getConnection().createStatement();
             var row = sql.executeQuery("SELECT qty, displayid FROM orders WHERE orderid = 'defaults'")) {
            assertTrue(row.next());
            assertEquals(1.0, row.getDouble("qty"));
            assertEquals("1", row.getString("displayid"));
        }
    }

    private static void shutdown(Session session, String engine) throws Exception {
        if (engine.equals("hsqldb")) {
            try (var sql = session.getConnection().createStatement()) { sql.execute("SHUTDOWN"); }
        }
        session.close();
    }
}
